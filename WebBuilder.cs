#if UNITY_EDITOR
using System.IO;
using System.Linq;
using UnityEditor;
using UnityEditor.Build.Reporting;
using UnityEngine;

namespace UltimateDrive.EditorTools
{
    /// <summary>
    /// WebGL builds for Vercel.
    /// Menu: UltimateDrive > Build > WebGL (writes to the web/ folder at the repo root, ready to commit or deploy).
    /// CI:   -executeMethod UltimateDrive.EditorTools.WebBuilder.BuildForCi   (used by the GitHub Actions workflow).
    /// </summary>
    public static class WebBuilder
    {
        [MenuItem("UltimateDrive/Build/WebGL (to web/ folder for Vercel)")]
        public static void BuildMenu()
        {
            string outDir = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "web"));
            if (!Build(outDir)) { EditorUtility.DisplayDialog("WebGL build", "Build failed. See the Console.", "OK"); return; }
            EditorUtility.RevealInFinder(outDir);
            Debug.Log("[WebGL] Done: " + outDir + "  (commit this folder, or deploy it with Vercel)");
        }

        // The workflow passes "-udOut web"; the path is relative to the project root. Defaults to web/.
        public static void BuildForCi()
        {
            string path = Arg("-udOut");
            if (string.IsNullOrEmpty(path)) path = "web";
            string full = Path.IsPathRooted(path) ? path : Path.GetFullPath(Path.Combine(Application.dataPath, "..", path));
            if (!Build(full)) EditorApplication.Exit(1);
        }

        static bool Build(string outDir)
        {
            // scenes are generated by the setup tool, so a fresh checkout without them still builds
            if (!File.Exists("Assets/Scenes/Boot.unity")) ProjectSetup.CreateAll();
            ProjectSetup.ApplyProjectSettings();

            string[] scenes = EditorBuildSettings.scenes.Where(s => s.enabled).Select(s => s.path).ToArray();
            if (scenes.Length == 0) { Debug.LogError("[WebGL] No scenes in Build Settings."); return false; }

            Directory.CreateDirectory(outDir);
            var opts = new BuildPlayerOptions
            {
                scenes = scenes,
                locationPathName = outDir,
                target = BuildTarget.WebGL,
                options = BuildOptions.None
            };
            var report = BuildPipeline.BuildPlayer(opts);
            Debug.Log("[WebGL] Result: " + report.summary.result + ", size " + (report.summary.totalSize / (1024 * 1024)) + " MB");
            bool ok = report.summary.result == BuildResult.Succeeded;
            if (ok) InstallIndexPage(outDir);
            return ok;
        }

        // Unity writes its own index.html; replace it with the branded page from WebTemplate/index.html.
        // The page needs the build name, which Unity takes from the output folder name.
        static void InstallIndexPage(string outDir)
        {
            string src = Path.GetFullPath(Path.Combine(Application.dataPath, "..", "WebTemplate", "index.html"));
            if (!File.Exists(src)) { Debug.LogWarning("[WebGL] WebTemplate/index.html not found; keeping Unity's default page."); return; }
            string name = Path.GetFileName(outDir.TrimEnd(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar));
            File.WriteAllText(Path.Combine(outDir, "index.html"), File.ReadAllText(src).Replace("__BUILD_NAME__", name));
            Debug.Log("[WebGL] Installed custom index.html (build name '" + name + "').");
        }

        static string Arg(string name)
        {
            var a = System.Environment.GetCommandLineArgs();
            for (int i = 0; i < a.Length - 1; i++) if (a[i] == name) return a[i + 1];
            return null;
        }
    }
}
#endif
